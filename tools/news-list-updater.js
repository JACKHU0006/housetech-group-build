/**
 * HouseTech Group - news.astro 列表自动更新器
 * 扫描 src/pages/news/ 目录，自动生成/更新 news.astro 列表页面
 */

import fs from 'fs';
import path from 'path';

const NEWS_DIR = path.resolve('src/pages/news');
const LIST_FILE = path.resolve('src/pages/news.astro');

const MONTH_ORDER = {
  'January': 1, 'February': 2, 'March': 3, 'April': 4,
  'May': 5, 'June': 6, 'July': 7, 'August': 8,
  'September': 9, 'October': 10, 'November': 11, 'December': 12,
};

function parseArticleFrontmatter(content) {
  const match = content.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return null;
  const fm = match[1];
  const titleMatch = fm.match(/^const\s+title\s*=\s*['"`]([^'"`]+)['"`]/m);
  if (!titleMatch) return null;
  const titleRaw = titleMatch[1];
  const cleanTitle = titleRaw.replace(/\s*-\s*HouseTech Group News\s*$/i, '').trim();

  const descMatch = fm.match(/^const\s+description\s*=\s*['"`]([^'"`]+)['"`]/m);
  const description = descMatch ? descMatch[1] : '';

  const categoryMatch = content.match(/<span class="article-category">([^<]+)<\/span>/);
  const category = categoryMatch ? categoryMatch[1].trim() : 'News';

  const dateMatch = content.match(/📅\s*([A-Za-z]+)\s+(\d{4})/);
  let dateStr = '';
  let sortKey = 0;
  if (dateMatch) {
    const month = dateMatch[1];
    const year = parseInt(dateMatch[2], 10);
    dateStr = `${month} ${year}`;
    sortKey = year * 100 + (MONTH_ORDER[month] || 0);
  }

  return { title: cleanTitle, description, category, date: dateStr, sortKey };
}

function scanArticles() {
  if (!fs.existsSync(NEWS_DIR)) return [];

  const files = fs.readdirSync(NEWS_DIR).filter(f => f.endsWith('.astro'));
  const articles = [];

  for (const file of files) {
    const fullPath = path.join(NEWS_DIR, file);
    const content = fs.readFileSync(fullPath, 'utf8');
    const meta = parseArticleFrontmatter(content);
    if (!meta) continue;

    const slug = file.replace(/\.astro$/, '');
    articles.push({
      slug,
      ...meta,
    });
  }

  articles.sort((a, b) => b.sortKey - a.sortKey);
  return articles;
}

function escapeForObject(str) {
  return str.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function generateListContent(articles) {
  const items = articles.map(a => {
    const imagePath = `/images/news/${a.slug}.svg`;
    const title = escapeForObject(a.title);
    const excerpt = escapeForObject(a.description || '');
    const category = escapeForObject(a.category);
    const date = escapeForObject(a.date);

    return `  {
    slug: '${a.slug}',
    title: '${title}',
    category: '${category}',
    date: '${date}',
    excerpt: '${excerpt}',
    image: '${imagePath}',
    gradient: 'linear-gradient(135deg, #0066ff, #0a2540)',
  },`;
  }).join('\n');

  return `---
import Layout from '../layouts/Layout.astro';
import Header from '../components/Header.astro';
import Footer from '../components/Footer.astro';

const title = 'News - HouseTech Group | Latest Updates & Industry Insights';
const description = 'Stay updated with HouseTech Group latest news, product launches, industry trends, and company events in the kitchen appliance sector.';

// News articles data - auto-generated by news-auto-generator
// Last updated: ${new Date().toISOString().split('T')[0]}
// Total articles: ${articles.length}
const newsArticles = [
${items}
];
---

<Layout title={title} description={description}>
  <Header activeNav="news" />

  <!-- Page Hero -->
  <section class="page-hero">
    <div class="container">
      <h1 class="hero-title">News & Insights</h1>
      <p class="hero-subtitle">Stay updated with HouseTech Group latest product launches, technology innovations, and global partnerships</p>
      <nav class="breadcrumb">
        <a href="/">Home</a> / <span>News</span>
      </nav>
    </div>
  </section>

  <!-- News List -->
  <section class="content-section">
    <div class="container">
      <div class="news-grid" style="display:grid;grid-template-columns:repeat(auto-fill,minmax(320px,1fr));gap:var(--spacing-lg);">
        {newsArticles.map((article) => (
          <a href={\`/news/\${article.slug}\`} class="news-card" style="background:var(--color-bg-elevated);border-radius:var(--radius-lg);overflow:hidden;transition:transform 0.2s,box-shadow 0.2s;box-shadow:var(--shadow-sm);text-decoration:none;color:inherit;display:flex;flex-direction:column;">
            <div style={\`width:100%;aspect-ratio:16/9;background:\${article.gradient};display:flex;align-items:center;justify-content:center;\`}>
              <img src={article.image} alt={article.title} loading="lazy" width="400" height="225" style="width:100%;height:100%;object-fit:cover;"/>
            </div>
            <div style="padding:var(--spacing-md);display:flex;flex-direction:column;flex:1;">
              <div style="display:flex;justify-content:space-between;align-items:center;margin-bottom:var(--spacing-xs);">
                <span style="font-size:0.8rem;color:var(--color-accent);font-weight:600;text-transform:uppercase;letter-spacing:0.5px;">{article.category}</span>
                <span style="font-size:0.8rem;color:var(--color-text-muted);">{article.date}</span>
              </div>
              <h3 style="font-size:1.1rem;font-weight:700;margin:0 0 var(--spacing-xs);line-height:1.4;">{article.title}</h3>
              <p style="font-size:0.9rem;color:var(--color-text-secondary);margin:0;line-height:1.5;flex:1;">{article.excerpt}</p>
            </div>
          </a>
        ))}
      </div>
    </div>
  </section>

  <Footer />
</Layout>
`;
}

export function updateNewsList() {
  console.log('📰 Scanning news articles...');
  const articles = scanArticles();
  console.log(`   Found ${articles.length} articles`);

  if (articles.length === 0) {
    console.log('   ⚠️  No articles found, skipping update');
    return false;
  }

  const content = generateListContent(articles);
  fs.writeFileSync(LIST_FILE, content, 'utf8');
  console.log(`   ✅ Updated ${LIST_FILE}`);
  return true;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  updateNewsList();
}
